#!/usr/bin/env node
/**
 * Desk story text per language.
 *
 * The released desk stories (content/desk-stories-v1.json, seeded by
 * migration 0029) keep their ids, choices and order in the database. Each file
 * in content/desk-stories/i18n/ gives complete Spanish (Latin America),
 * Brazilian Portuguese or French text for every story, by id.
 *
 *   node tool/generate-desk-story-texts.mjs          writes apps/api/src/desk-story-texts.generated.ts
 *   node tool/generate-desk-story-texts.mjs --check  fails if that file is stale or a translation is wrong
 *
 * Checks, as for workdays: every story and choice id exists in the seed,
 * every field is translated, trimmed and free of dashes used as punctuation,
 * and every field carries exactly the English numbers.
 */
import {readFile, writeFile} from 'node:fs/promises';
import {dirname, resolve} from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {overlay, sameNumbers} from './generate-workday-texts.mjs';

const defaultRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const DESK_LOCALES = Object.freeze(['es', 'pt', 'fr']);
export const DESK_OUTPUT = 'apps/api/src/desk-story-texts.generated.ts';
const SEED = 'content/desk-stories-v1.json';

function fail(message) { throw new Error(`Desk story text: ${message}`); }

/** The translatable text of one seeded story, keyed by stable ids. */
export function storyText(story) {
  return {title: story.title, body: story.body,
    choices: Object.fromEntries(story.choices.map(choice => [choice.id, {label: choice.label, outcome: choice.outcome, takeaway: choice.takeaway}]))};
}

export async function buildDeskStoryTexts(root = defaultRoot) {
  const seed = JSON.parse(await readFile(resolve(root, SEED), 'utf8'));
  const base = Object.fromEntries(seed.stories.map(story => [story.id, storyText(story)]));
  const texts = {en: base};
  for (const locale of DESK_LOCALES) {
    const file = JSON.parse(await readFile(resolve(root, `content/desk-stories/i18n/${seed.version}.${locale}.json`), 'utf8'));
    if (file.schemaVersion !== 1 || file.locale !== locale || file.contentVersion !== seed.version) fail(`${locale}: header does not match the seed`);
    for (const id of Object.keys(file.stories ?? {})) if (!Object.hasOwn(base, id)) fail(`${locale}: ${id} is not a released desk story`);
    texts[locale] = Object.fromEntries(Object.keys(base).map(id => {
      try {
        const text = overlay(base[id], file.stories?.[id], `${locale}.${id}`, true);
        sameNumbers(base[id], text, `${locale}.${id}`);
        return [id, text];
      } catch (error) { fail(error instanceof Error ? error.message.replace(/^Workday text: /, '').replace('released workday', 'released desk story') : String(error)); }
    }));
  }
  return {contentVersion: seed.version, texts};
}

export function renderDeskStories({contentVersion, texts}) {
  return `// Generated by tool/generate-desk-story-texts.mjs from content/. Do not edit.
// Text only: ids, choices and order come from the released desk stories in the database.
export type DeskStoryLanguage = 'en' | ${DESK_LOCALES.map(locale => `'${locale}'`).join(' | ')};
export interface DeskStoryText {
  readonly title: string; readonly body: string;
  readonly choices: Readonly<Record<string, {readonly label: string; readonly outcome: string; readonly takeaway: string}>>;
}
export const DESK_STORY_CONTENT_VERSION = ${JSON.stringify(contentVersion)};
export const DESK_STORY_TEXTS: Readonly<Record<DeskStoryLanguage, Readonly<Record<string, DeskStoryText>>>> = ${JSON.stringify(texts, null, 1)};
`;
}

async function main() {
  const check = process.argv.includes('--check');
  const built = renderDeskStories(await buildDeskStoryTexts());
  const path = resolve(defaultRoot, DESK_OUTPUT);
  if (check) {
    const current = await readFile(path, 'utf8').catch(() => '');
    if (current !== built) fail(`${DESK_OUTPUT} is stale; run node tool/generate-desk-story-texts.mjs`);
    process.stdout.write(`Desk story text checked: en, ${DESK_LOCALES.join(', ')}.\n`);
  } else {
    await writeFile(path, built);
    process.stdout.write(`Wrote ${DESK_OUTPUT}.\n`);
  }
}
if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  main().catch(error => { process.stderr.write(`${error.message}\n`); process.exitCode = 1; });
}
