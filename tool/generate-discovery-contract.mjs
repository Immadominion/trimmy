// Generates one real discovery response from the API's own reader and freezes it
// as a contract the mobile parser must accept.
//
// The two ends were tested independently: the server against a stubbed upstream
// provider, the app against its own fixtures. Nothing proved they agreed, and
// the mobile parser requires an exact key set, so a single added or renamed
// field would make every search fail in production while both suites stayed
// green. This file is the shared witness.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { TokensStockDiscovery } from '../apps/api/src/stock-discovery.ts';

const OUTPUT = new URL('../contracts/stock-discovery-v1.json', import.meta.url);
const now = Date.parse('2026-09-14T16:00:00.000Z');

// Public mints, used as shape only. They do not stand for the invented issuers.
const mintA = 'So11111111111111111111111111111111111111112';
const mintB = 'EPjFWdd5AufqSSqeM2qN1xzybapC8G4wEGGkZwyTDt1v';

const market = (overrides = {}) => ({
  price: 101.25, liquidity: 8000, volume24hUSD: 1000, decimals: 9,
  source: 'clickhouse_trades', metricsSource: 'clickhouse_trades',
  asOf: 1789380000, lastFetchedAt: 1789380050000, lastTradeAt: 1789379999, ...overrides,
});

const variantA = {
  variantId: 'fixture-issuer-a', mint: mintA, kind: 'tokenized_equity',
  issuer: 'Fixture Issuer A', label: 'Fixture A', name: 'Example Company A',
  symbol: 'EX-A', stockVariantTier: 'cash_redeemable', advisory: null, market: market(),
};

// A flagged sibling, so the contract carries an advisory rather than only the
// happy path the app would otherwise be the only side to have exercised.
const variantB = {
  variantId: 'fixture-issuer-b', mint: mintB, kind: 'tokenized_equity',
  issuer: 'Fixture Issuer B', label: 'Fixture B', name: 'Example Company B',
  symbol: 'EX-B', stockVariantTier: 'cash_redeemable',
  advisory: {status: 'caution', reason: 'Provider flagged low liquidity', since: 1788912000000},
  market: market({price: 98, liquidity: 500, decimals: 6}),
};

// A flagged variant must be matched by an asset-level advisory, and the server
// checks that the two agree, so the contract carries both.
const flag = {
  mint: mintB, variantId: 'fixture-issuer-b', status: 'caution',
  reason: 'Provider flagged low liquidity', since: 1788912000000,
};

const asset = {
  assetId: 'example-company', name: 'Example Company', symbol: 'EX', category: 'equity',
  primaryVariant: variantA, variants: [variantA, variantB], advisories: [flag],
};

const upstream = {
  search: {query: 'Example Company', category: 'equity', primaryVariantStrategy: 'liquidity', results: [asset]},
  variants: {assetId: 'example-company', sortBy: 'liquidity', variants: [variantA, variantB]},
};

function reader(payload) {
  return new TokensStockDiscovery({
    apiKey: 'contract-generator-key-not-live',
    now: () => now,
    fetch: async () => Response.json(payload),
  });
}

const search = await reader(upstream.search).search({query: 'Example Company', limit: 5});
const variants = await reader(upstream.variants).variants({assetId: 'example-company'});

const contract = {
  schemaVersion: 1,
  note: 'Generated by tool/generate-discovery-contract.mjs. Do not edit by hand.',
  generatedAt: new Date(now).toISOString(),
  search,
  variants,
};
const serialized = `${JSON.stringify(contract, null, 2)}\n`;
const digest = createHash('sha256').update(serialized).digest('hex');

if (process.argv.includes('--check')) {
  let existing = '';
  try { existing = readFileSync(OUTPUT, 'utf8'); } catch { existing = ''; }
  if (existing !== serialized) {
    process.stderr.write('contracts/stock-discovery-v1.json is stale. Run npm run generate:discovery-contract.\n');
    process.exit(1);
  }
  process.stdout.write(`discovery contract current (sha256 ${digest})\n`);
} else {
  writeFileSync(OUTPUT, serialized);
  process.stdout.write(`wrote contracts/stock-discovery-v1.json (sha256 ${digest})\n`);
}
